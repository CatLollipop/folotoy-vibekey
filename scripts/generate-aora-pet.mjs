#!/usr/bin/env node
/** 从固定的官方模拟器提取 Dot 关键几何与调度参数；不采样、保存或播放动画帧序列。 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as Aora from '../app/VibeKey/Pet/Resources/AoraPet.bundle/engine.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'firmware/main/ib_pet_data.h');
const rings = [], ringIds = new Map(), poses = [], poseIds = new Map();
const q = n => Math.round(n * 64);
function ringId(points) {
  const p = points.map(([x,y]) => [q(x),q(y)]);
  const key = JSON.stringify(p);
  if (!ringIds.has(key)) {ringIds.set(key,rings.length);rings.push(p);}
  return ringIds.get(key);
}
function flatten(points, t) {
  const [a,b,c,d] = t.matrix;
  return points.map(([x,y]) => [t.x + a*(x-t.pivotX)+c*(y-t.pivotY),t.y+b*(x-t.pivotX)+d*(y-t.pivotY)]);
}
function extract(state, expression) {
  const sim = Aora.createSimulation({shape:'circle',face:'capsule',state,seed:'passport-dot',
    still:{expression},poseHome:{turn:0,tilt:0,roll:0}});
  const frame = sim.snapshot(), geo = frame.face.geometry;
  const shapes = [];let layerIndex=0,faceAxis=null;
  for (const design of geo?.drawn ?? []) {
    if (design.opacity < .5) continue;
    const l=design.left.transform,r=design.right.transform;
    const dr=Math.round((r.y-l.y)/10),axis=Math.round(l.x/10+r.x/10+4)/2;
    const reach=Math.round((r.x-l.x)/10)/2,row=Math.round(l.y/10+r.y/10+4-dr)/2;
    faceAxis=axis;
    const linear=l.matrix.map((v,i)=>(v+r.matrix[i]*(i===1||i===2?-1:1))/2);
    for (const [group,eye] of [[1,design.left],[2,design.right]]) {
      if (!eye?.visible) continue;
      for (const layer of eye.layers) {
        if (layer.opacity < .5) continue;
        const layerId=layerIndex++;
        const paint = layer.paint === 'feature' ? 2 : layer.paint === 'gold' ? 3 : 4;
        for (const ring of layer.rings) {
          // 官方drawn.ts的共用镜像投影与半格锚点，先变成规范关键轮廓，运行时C再做动态变换。
          const matrix=linear.map((v,i)=>v*(group===2&&(i===1||i===2)?-1:1));
          const [a,b,c,d]=matrix,t=eye.transform;
          const px=(axis+(group===1?-reach:reach)-2)*10,py=(row+(group===2?dr:0)-2)*10;
          const points=ring.map(([x,y])=>[px+a*(x-t.pivotX)+c*(y-t.pivotY),py+b*(x-t.pivotX)+d*(y-t.pivotY)]);
          shapes.push({ring:ringId(points),group,paint,layer:layerId});
        }
      }
    }
  }
  if (geo?.mouth?.opacity >= .5 && geo.mouth.points.length >= 3) {
    const points=flatten(geo.mouth.points,geo.mouth.transform),xs=points.map(p=>p[0]/10+2),ys=points.map(p=>p[1]/10+2);
    const cx=(Math.min(...xs)+Math.max(...xs))/2,cy=(Math.min(...ys)+Math.max(...ys))/2;
    const ax=faceAxis!==null&&Math.abs(cx-faceAxis)<1.5?faceAxis:Math.round(cx*2)/2,ay=Math.round(cy*2)/2;
    shapes.push({ring:ringId(points.map(([x,y])=>[x+(ax-cx)*10,y+(ay-cy)*10])),group:3,paint:2,layer:layerIndex++});
  }
  const key = JSON.stringify(shapes);
  if (!poseIds.has(key)){poseIds.set(key,poses.length);poses.push(shapes);}
  const body = ringId(frame.body.outline);
  sim.dispose();
  return {pose:poseIds.get(key),body};
}
const states = Aora.CHARACTER_STATES.map(state=>{
  const expressions=Aora.STATE_CUTE_EYES[state];
  const refs=expressions.map(expr=>extract(state,expr).pose);
  return {state,refs,blink:Aora.STATE_BLINK_MS[state]??[0,0],cycle:Aora.STATE_EYE_SWITCH_MS[state]??[0,0]};
});
const body=extract('idle','dot').body;
let text = `/* Generated by scripts/generate-aora-pet.mjs.\n * Aora Bot 0.2.0 / 164ffa38b3c27a8512e7c09cfceb7cf0c98f5144\n * Copyright (c) 2026 sam70361. Aora Bot License 1.1, see vendor/aora-bot/LICENSE.\n * 这里只存关键轮廓和状态参数，不存预烘动画帧。Q6 = 官方 shape-space 坐标 ×64。 */\n`;
text += '#pragma once\n#include <stdint.h>\n';
text += 'typedef struct {int16_t x,y;} ib_pet_point_t;\n';
text += 'typedef struct {uint16_t first,count;} ib_pet_ring_t;\n';
text += 'typedef struct {uint16_t ring;uint8_t group,paint,layer;} ib_pet_part_t;\n';
text += 'typedef struct {uint16_t first,count;} ib_pet_pose_t;\n';
text += 'typedef struct {const char *name;uint16_t poses[6];uint8_t count;uint16_t blink_min,blink_max,cycle_min,cycle_max;} ib_pet_definition_t;\n';
const points=rings.flat();
text += 'static const ib_pet_point_t ib_pet_points[] = {'+points.map(p=>`{${p[0]},${p[1]}}`).join(',')+'};\n';
let at=0;
text += 'static const ib_pet_ring_t ib_pet_rings[] = {'+rings.map(r=>{const s=`{${at},${r.length}}`;at+=r.length;return s;}).join(',')+'};\n';
const parts=poses.flat();
text += 'static const ib_pet_part_t ib_pet_parts[] = {'+parts.map(p=>`{${p.ring},${p.group},${p.paint},${p.layer}}`).join(',')+'};\n';
at=0;
text += 'static const ib_pet_pose_t ib_pet_poses[] = {'+poses.map(p=>{const s=`{${at},${p.length}}`;at+=p.length;return s;}).join(',')+'};\n';
text += `#define IB_PET_BODY_RING ${body}\n#define IB_PET_DEFINITION_COUNT ${states.length}\n`;
text += 'static const ib_pet_definition_t ib_pet_definitions[] = {\n'+states.map(s=>`{"${s.state}",{${[...s.refs,...Array(6-s.refs.length).fill(0)].join(',')}},${s.refs.length},${s.blink.join(',')},${s.cycle.join(',')}}`).join(',\n')+'\n};\n';
fs.writeFileSync(out,text);
console.log(JSON.stringify({states:states.length,poses:poses.length,rings:rings.length,points:points.length,headerBytes:text.length,bodyRing:body}));

// 黄金数据来自官方JS，而不是C实现自身。这里只在host测试目录保留静态断言，设备不链接这些格点。
const enginePath=path.join(root,'app/VibeKey/Pet/Resources/AoraPet.bundle/engine.mjs');
const src=fs.readFileSync(enginePath,'utf8')+'\nexport {rasterise,createPaintTable,createScratch,pixelGrid,shadeHex};';
const internal=await import('data:text/javascript;base64,'+Buffer.from(src).toString('base64'));
const grid=internal.pixelGrid(24), fixtures=[];
for(const state of Aora.CHARACTER_STATES){
  const sim=Aora.createSimulation({shape:'circle',face:'capsule',state,seed:'passport-dot',still:true,poseHome:{turn:0,tilt:0,roll:0}});
  const table=internal.createPaintTable(),paint=new Uint16Array(grid.size*grid.size);
  const frame=sim.snapshot();frame.fx=null;frame.face.blush=0;
  frame.body={...frame.body,x:0,y:0,rotation:0,scaleX:1,scaleY:1};
  internal.rasterise(frame,{grid,shades:3,outline:true,variant:'dot',gradient:null,
    eye:{kind:'css',value:'#17181D'},face:{kind:'css',value:'#17181D'}},table,internal.createScratch(grid.size),paint);
  fixtures.push([...paint].map(id=>{
    if(!id)return 0;const tint=table.defs[id-1].tint;
    return tint.kind==='ink'||tint.kind==='css'&&tint.value!=='#17181D'&&!tint.value.includes('--aora-face-soft')?1:0;
  }));
  sim.dispose();
}
const golden=`/* Official Aora pixel raster fixture; generated, test-only. */\nstatic const unsigned char aora_golden[44][784]={\n${fixtures.map(x=>'{'+x.join(',')+'}').join(',\n')}\n};\n`;
fs.writeFileSync(path.join(root,'firmware/tests/ib_pet_golden.h'),golden);
const samples=[];
for(const state of Aora.CHARACTER_STATES)for(const t of [0,.42,2.7]){
  const value=Aora.behaviourFor(state)({t,clock:t,random:()=>.5,impulse:()=>{}});
  samples.push([Aora.CHARACTER_STATES.indexOf(state),t,value.tilt,value.x,value.y,value.squash]);
}
fs.writeFileSync(path.join(root,'firmware/tests/ib_pet_motion_golden.h'),
  '/* Official behaviourFor outputs, fixed times. */\nstatic const float motion_golden[][6]={\n'+samples.map(x=>'{'+x.map(v=>Number(v).toFixed(7)+'f').join(',')+'}').join(',\n')+'\n};\n');
console.log('official cream palette',Aora.getInkColor('cream','dark'),internal.shadeHex(Aora.getInkColor('cream','dark'),.3));
